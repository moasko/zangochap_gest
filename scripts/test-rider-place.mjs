import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
import ts from "typescript";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { NextRequest } = require("next/server");
let session = null, calls = 0;
const env = {};
const scope = { exports: {}, URL, URLSearchParams, AbortSignal, Date, process: { env }, fetch: async url => {
  calls++;
  assert.equal(url.hostname, "api.geoapify.com");
  assert.equal(url.searchParams.get("lang"), "fr");
  return { ok: true, json: async () => ({ results: [{ formatted: "Lieu fictif de validation" }] }) };
}, require: name => name === "@/modules/auth/actions" ? { getSession: async () => session } : require(name) };
vm.runInNewContext(ts.transpileModule(fs.readFileSync("app/api/admin/rider-tracking/place/route.ts", "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, scope);
const get = query => scope.exports.GET(new NextRequest("https://demo.test/api/admin/rider-tracking/place?" + query));
assert.equal((await get("lat=5&lon=-4")).status, 403);
session = { role: "livreur" };
assert.equal((await get("lat=5&lon=-4")).status, 403);
session = { role: "admin" };
for (const query of ["", "lat=&lon=0", "lat=91&lon=0", "lat=NaN&lon=0", "lat=0&lon=181"]) assert.equal((await get(query)).status, 400);
assert.equal((await get("lat=5&lon=-4")).status, 503);
assert.equal(calls, 0);
env.GEOAPIFY_API_KEY = "test-key-never-sent";
const first = await get("lat=5&lon=-4");
assert.equal(first.status, 200);
assert.equal(first.headers.get("cache-control"), "no-store");
assert.equal((await first.json()).label, "Lieu fictif de validation");
assert.equal((await get("lat=5&lon=-4")).status, 200);
assert.equal(calls, 1, "cache avoids repeated external requests");
assert.equal((await get("lat=6&lon=-4")).status, 429);
assert.equal(calls, 1, "rate limit enforced");
console.log("OK: place lookup roles, coordinates, missing configuration, cache and rate limit. No real network or database.");
